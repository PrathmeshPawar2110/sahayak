"""Write schemes and chunks to Postgres (TRD §8 step 5). Idempotent by content hash.

Re-indexing a source embeds and inserts only chunks whose hash is new, deletes chunks whose
hash disappeared from that source, and leaves everything else alone, so an unchanged source
costs one query and no embedding calls. The tsvector column is generated by Postgres.

Nothing here commits: the caller owns the transaction, normally one per scheme.
"""

import hashlib
from collections.abc import Sequence
from dataclasses import dataclass
from datetime import datetime
from typing import Any

from sqlalchemy import delete, func, select, update
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession

from sahayak.db.models import Scheme, SchemeChunk, SchemeStatus
from sahayak.ingestion.chunk import Chunk
from sahayak.ingestion.manifest import SchemeSpec
from sahayak.rag.embeddings import EmbeddingProvider

# Rows per INSERT: 10 bind parameters each keeps a statement far below asyncpg's 32767 limit.
INSERT_BATCH = 500


@dataclass(frozen=True)
class IndexStats:
    added: int = 0
    kept: int = 0
    removed: int = 0

    def __add__(self, other: "IndexStats") -> "IndexStats":
        return IndexStats(
            self.added + other.added, self.kept + other.kept, self.removed + other.removed
        )


@dataclass(frozen=True)
class SourceChunks:
    """The chunks of one manifest source, ready to index."""

    url: str  # the manifest URL, as passed to the chunker
    sha256: str  # of the fetched document
    chunks: Sequence[Chunk]


def embedding_input(scheme_name: str, chunk: Chunk) -> str:
    """Text embedded for a chunk. The scheme name and section give short chunks context."""
    return f"{scheme_name}: {chunk.section}\n{chunk.text}"


def sources_hash(source_hashes: Sequence[str]) -> str:
    """One hash over all of a scheme's source documents, to spot any change (M9 staleness)."""
    return hashlib.sha256("\n".join(sorted(source_hashes)).encode()).hexdigest()


async def index_scheme(
    session: AsyncSession,
    embedder: EmbeddingProvider,
    spec: SchemeSpec,
    sources: Sequence[SourceChunks],
    *,
    verified_at: datetime,
) -> IndexStats:
    """Bring one scheme's catalogue row and chunks in line with the manifest and its sources.

    `sources` may omit manifest sources that could not be fetched this run: their stored chunks
    are kept, and the scheme's `content_hash` and `last_verified_at` are left unchanged because
    the scheme was not fully verified. Chunks of sources no longer in the manifest are deleted.
    """
    languages = {str(source.url): source.language for source in spec.sources}
    unknown = sorted({source.url for source in sources} - languages.keys())
    if unknown:
        raise ValueError(f"{spec.id}: sources not in the manifest: {unknown}")
    if len({source.url for source in sources}) != len(sources):
        raise ValueError(f"{spec.id}: a source is listed twice")

    complete = len(sources) == len(languages)
    await upsert_scheme(
        session,
        spec,
        verified_at=verified_at if complete else None,
        content_hash=sources_hash([source.sha256 for source in sources]) if complete else None,
    )

    stats = IndexStats(
        removed=await remove_unlisted_sources(
            session, scheme_id=spec.id, source_urls=list(languages)
        )
    )
    for source in sources:
        name = getattr(spec.names, languages[source.url].value) or spec.names.en
        stats += await index_source_chunks(
            session,
            embedder,
            scheme_id=spec.id,
            scheme_name=name,
            source_url=source.url,
            chunks=source.chunks,
        )
    return stats


async def upsert_scheme(
    session: AsyncSession,
    spec: SchemeSpec,
    *,
    verified_at: datetime | None,
    content_hash: str | None,
) -> Scheme:
    """Create or update the catalogue row from the manifest.

    The lifecycle status is never reset: a scheme approved as `active` stays active when it is
    re-ingested. New schemes start as `provisional` until their rules are approved (TRD §8A).
    `verified_at` and `content_hash` are left as stored when None.
    """
    values: dict[str, Any] = {
        "name_en": spec.names.en,
        "name_hi": spec.names.hi,
        "name_mr": spec.names.mr,
        "aliases": list(spec.aliases),
        "ministry": spec.ministry,
        "level": spec.level.value,
        "state": spec.state,
        "benefits": spec.benefits,
        "application_url": str(spec.application_url) if spec.application_url else None,
        "source_url": spec.primary_source_url,
    }
    if verified_at is not None:
        values["last_verified_at"] = verified_at
    if content_hash is not None:
        values["content_hash"] = content_hash
    statement = insert(Scheme).values(id=spec.id, status=SchemeStatus.PROVISIONAL.value, **values)
    # ON CONFLICT DO UPDATE skips the ORM's `onupdate`, so set `updated_at` explicitly.
    await session.execute(
        statement.on_conflict_do_update(
            index_elements=[Scheme.id], set_={**values, "updated_at": func.now()}
        )
    )
    scheme = await session.get(Scheme, spec.id, populate_existing=True)
    if scheme is None:  # pragma: no cover - the upsert above guarantees the row
        raise RuntimeError(f"scheme {spec.id} missing after upsert")
    return scheme


async def index_source_chunks(
    session: AsyncSession,
    embedder: EmbeddingProvider,
    *,
    scheme_id: str,
    scheme_name: str,
    source_url: str,
    chunks: Sequence[Chunk],
) -> IndexStats:
    """Make the stored chunks of one (scheme, source) pair equal to `chunks`."""
    strays = [
        c.chunk_index for c in chunks if (c.scheme_id, c.source_url) != (scheme_id, source_url)
    ]
    if strays:
        raise ValueError(f"chunks {strays} do not belong to {scheme_id} / {source_url}")

    rows = await session.execute(
        select(SchemeChunk.content_hash, SchemeChunk.chunk_index).where(
            SchemeChunk.scheme_id == scheme_id, SchemeChunk.source_url == source_url
        )
    )
    existing: dict[str, int] = {content_hash: index for content_hash, index in rows}
    wanted = {chunk.content_hash: chunk for chunk in chunks}

    stale = existing.keys() - wanted.keys()
    if stale:
        await session.execute(
            delete(SchemeChunk).where(
                SchemeChunk.scheme_id == scheme_id, SchemeChunk.content_hash.in_(stale)
            )
        )

    new = [chunk for content_hash, chunk in wanted.items() if content_hash not in existing]
    if new:
        vectors = await embedder.embed_passages([embedding_input(scheme_name, c) for c in new])
        rows_to_insert = [
            {
                "id": chunk.id,
                "scheme_id": scheme_id,
                "source_url": source_url,
                "section": chunk.section,
                "language": chunk.language.value,
                "chunk_index": chunk.chunk_index,
                "text": chunk.text,
                "token_count": chunk.token_count,
                "content_hash": chunk.content_hash,
                "embedding": vector,
            }
            for chunk, vector in zip(new, vectors, strict=True)
        ]
        for start in range(0, len(rows_to_insert), INSERT_BATCH):
            await session.execute(
                insert(SchemeChunk)
                .values(rows_to_insert[start : start + INSERT_BATCH])
                .on_conflict_do_nothing(index_elements=["scheme_id", "content_hash"])
            )

    # Kept chunks may have moved within the document; keep their order current.
    for content_hash, chunk in wanted.items():
        if content_hash in existing and existing[content_hash] != chunk.chunk_index:
            await session.execute(
                update(SchemeChunk)
                .where(SchemeChunk.scheme_id == scheme_id, SchemeChunk.content_hash == content_hash)
                .values(chunk_index=chunk.chunk_index)
            )

    return IndexStats(added=len(new), kept=len(wanted) - len(new), removed=len(stale))


async def remove_unlisted_sources(
    session: AsyncSession, *, scheme_id: str, source_urls: Sequence[str]
) -> int:
    """Drop chunks of sources that were removed from the manifest entry."""
    result = await session.execute(
        delete(SchemeChunk)
        .where(SchemeChunk.scheme_id == scheme_id, SchemeChunk.source_url.not_in(source_urls))
        .returning(SchemeChunk.id)
    )
    return len(result.all())
